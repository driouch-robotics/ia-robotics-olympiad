export function t(language, key, values = {}) {
  const template = ui[language]?.[key] ?? ui.ar[key] ?? key;
  return Object.entries(values).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, value), template);
}

export function getLevelCopy(levelId, language) {
  return levelCopy[language]?.[levelId] ?? levelCopy.ar[levelId];
}

export function getCategoryLabel(category, language) {
  return categoryCopy[language]?.[category] ?? categoryCopy.ar[category];
}

export function getTypeLabel(type, language) {
  return typeCopy[language]?.[type] ?? typeCopy.ar[type] ?? type;
}

function getQuestionTranslation(question, language) {
  if (language !== "fr") return null;
  return question.fr ?? questionFr[question.id] ?? null;
}

export function getQuestionPrompt(question, language) {
  return getQuestionTranslation(question, language)?.prompt ?? question.prompt;
}

export function getQuestionExplanation(question, language) {
  return getQuestionTranslation(question, language)?.explanation ?? question.explanation;
}

export function getBooleanLabel(value, language) {
  return value ? t(language, "true") : t(language, "false");
}

export function getOptionLabel(question, value, language) {
  if (question.type === "boolean") return getBooleanLabel(value, language);
  if (language !== "fr") return value;

  const translated = getQuestionTranslation(question, language);
  if (!translated) return value;

  if (question.options && translated.options) {
    const index = question.options.indexOf(value);
    if (index >= 0) return translated.options[index] ?? value;
  }

  if (question.pairs && translated.pairs) {
    const rightIndex = question.pairs.findIndex((pair) => pair.right === value);
    if (rightIndex >= 0) return translated.pairs[rightIndex]?.right ?? value;
  }

  return value;
}

export function getPairLeftLabel(question, value, language) {
  if (language !== "fr") return value;
  const translated = getQuestionTranslation(question, language);
  if (!translated?.pairs) return value;
  const index = question.pairs.findIndex((pair) => pair.left === value);
  return index >= 0 ? translated.pairs[index]?.left ?? value : value;
}

export function getAnswerLabel(question, language) {
  if (question.type === "choice") return getOptionLabel(question, question.answer, language);
  if (question.type === "boolean") return getBooleanLabel(question.answer, language);
  if (question.type === "multi") return question.answers.map((item) => getOptionLabel(question, item, language)).join(language === "fr" ? ", " : "، ");
  if (question.type === "order") return question.correctOrder.map((item) => getOptionLabel(question, item, language)).join(" ← ");
  if (question.type === "match") {
    return question.pairs
      .map((pair) => `${getPairLeftLabel(question, pair.left, language)}: ${getOptionLabel(question, pair.right, language)}`)
      .join(language === "fr" ? ", " : "، ");
  }
  return "";
}
